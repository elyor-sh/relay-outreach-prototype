const PLURALS = { ru: new Intl.PluralRules('ru-RU'), en: new Intl.PluralRules('en-US') };
const RU_FORM = { one: 0, few: 1, many: 2, other: 2 };
const missingKeys = new Set();

/** Translate `key` into the current UI language with `{param}` interpolation and plurals. */
function t(key, vars) {
  const entry = I18N[key];
  if (!entry) {
    if (!missingKeys.has(key)) { missingKeys.add(key); console.warn(`[i18n] missing key: ${key}`); }
    return key;
  }
  const lang = (typeof state !== 'undefined' && state.ui.lang) || 'ru';
  let s = entry[lang === 'en' ? 1 : 0];
  if (s.includes('|') && vars && typeof vars.n === 'number') {
    const forms = s.split('|');
    const cat = PLURALS[lang].select(vars.n);
    const idx = lang === 'en' ? (cat === 'one' ? 0 : 1) : RU_FORM[cat];
    s = forms[Math.min(idx, forms.length - 1)];
  }
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

if (typeof module === 'object' && module && module.exports) module.exports = { I18N, t };
